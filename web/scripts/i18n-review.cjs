// Regenerates docs/i18n-review.md from src/i18n/*.json and docs/glossary.md so it cannot drift.
// The "Native reviewer" columns are EMPTY: no native review has happened. Run: npm run i18n:review
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'src', 'i18n'), docs = path.join(__dirname, '..', '..', 'docs');
const L = Object.fromEntries(['en', 'es', 'it'].map((l) => [l, JSON.parse(fs.readFileSync(path.join(dir, l + '.json'), 'utf8'))]));
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const gloss = fs.readFileSync(path.join(docs, 'glossary.md'), 'utf8').split('\n').filter((l) => l.startsWith('|')).slice(2)
  .map((l) => l.replace(/^\||\|$/g, '').split(/(?<!\\)\|/).map((c) => c.trim()));
const FLAG = { // term -> note on regional variants / uncertainty (verify with a native speaker)
  check: 'es: "pasar" (ES/LatAm) vs "pasar/check" (many LatAm sites keep "check"). it: "parola" is standard Italian poker, "check" also common online.',
  fold: 'es: "retirarse" vs "tirar/no ir/foldear" (LatAm). it: "passa" vs "fold"; "passa" can be confused with check ("parola").',
  call: 'es: "igualar" vs "pagar/ver" (regional). it: "chiama" standard.',
  bet: 'es: "apuesta" vs "apostar" as verb. it: "puntata" vs "bet".',
  raise: 'es: "subida" vs "subir/resubir" (noun vs verb on buttons). it: "rilancio" standard.',
  pot: 'es: "bote" (Spain) vs "pozo" (Argentina/LatAm). it: "piatto" standard.',
  stack: 'Left in English in both; es also "fichas", it also "stack/fiches".',
  range: 'Left in English in both; es also "rango", it also "range" (common).',
  equity: 'Not in current UI keys unless listed below; es "equity"/"equidad", it "equity" (verify before use).',
  river: 'English loanword in both; es also "río"; verify.',
  turn: 'English loanword in both; es also "giro/turn", it "turn".',
  flop: 'English loanword in both; verify.',
  ev: 'es/it: "EV" kept; es also "valor esperado", it "valore atteso".',
  streak: 'es: "racha" (ok); it: "serie" (alt "striscia").',
  drill: 'es: "práctica" vs "ejercicio/entrenamiento". it: "esercizio" vs "allenamento". Mixed with "Practice" naming.',
  practice: 'See drill.',
};
const flagFor = (txt) => { const n = []; for (const [k, v] of Object.entries(FLAG)) if (new RegExp('\\b' + (k === 'ev' ? 'EV' : k) + '\\b', k === 'ev' ? '' : 'i').test(txt)) n.push(`**${k}**: ${v}`); return n.join(' '); };
let o = `# i18n review sheet (es / it)

GENERATED by \`npm run i18n:review\` (web/scripts/i18n-review.cjs) from \`web/src/i18n/*.json\` and \`docs/glossary.md\`. Do not edit by hand.

**Status: NOT natively reviewed.** The "Native reviewer" columns are blank on purpose; a native speaker must fill OK or the fix. Terms marked in "Flag / regional note" are most likely to be wrong or regional (es: Spain vs Latin America; it: online vs live-room usage).

## Glossary terms (docs/glossary.md)

| en | es | it | Flag / regional note | es reviewer OK/fix | it reviewer OK/fix |
|---|---|---|---|---|---|
`;
for (const [en, es, it] of gloss) o += `| ${cell(en)} | ${cell(es)} | ${cell(it)} | ${cell(flagFor(en))} |  |  |\n`;
o += `\n## All UI strings (src/i18n)\n\n| key | en | es | it | Flag / regional note | es reviewer OK/fix | it reviewer OK/fix |\n|---|---|---|---|---|---|---|\n`;
for (const k of Object.keys(L.en)) o += `| \`${k}\` | ${cell(L.en[k])} | ${cell(L.es[k])} | ${cell(L.it[k])} | ${cell(flagFor(L.en[k]))} |  |  |\n`;
fs.writeFileSync(path.join(docs, 'i18n-review.md'), o);
console.log('wrote docs/i18n-review.md', Object.keys(L.en).length, 'keys,', gloss.length, 'glossary rows');
